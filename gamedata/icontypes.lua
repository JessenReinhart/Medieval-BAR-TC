-- Medieval radar / minimap icon types.
--
-- The engine loads this file once at boot (CIconHandler::LoadIcons in
-- rts/Rendering/IconHandler.cpp) and each UnitDef selects one entry through
-- its `iconType` field. A unit's icon is both its radar blip and the sprite
-- the engine substitutes for the 3D mesh when the camera is zoomed out far
-- enough (UnitIconDist).
--
-- Supported keys, as parsed by CIconHandler::LoadIcons:
--   bitmap        (string)  RGBA image, resolved through the VFS
--   size          (float)   icon size multiplier, default 1.0
--   distance      (float)   squared internally and compared against the
--                           squared camera distance to decide when the icon
--                           replaces the mesh, default 1.0
--   radiusAdjust  (bool)    scale the icon with the unit's collision radius
--                           (divided by IconData::GetRadiusScale() == 30)
--   u0/v0/u1/v1   (floats)  sub-rect when several icons share one atlas image
--   drawOrder     (float)   >0 draws the icon above others
--
-- The bitmaps are white-on-transparent so the renderer can tint them with the
-- owner's team colour. They are generated by
-- tools/assets/generate_minimap_icons.py; the engine falls back to
-- bitmaps/defaultradardot.png for any icon type whose bitmap is missing, so a
-- packaging mistake degrades to a plain dot instead of an error.

